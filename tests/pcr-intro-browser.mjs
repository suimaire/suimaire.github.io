import { resolve } from 'node:path';

// Runs in both engines at every viewport through pcr-browser.mjs.
export async function exerciseIntro(page, width, engine, check, output) {
  check(await page.locator('#export-record').isHidden() && await page.locator('#print-filled').isHidden(), 'only two closed document menus');
  await page.locator('#record-menu > summary').focus(); await page.keyboard.press('Enter');
  check(await page.locator('#export-record').isVisible(), 'keyboard opens record menu');
  await page.keyboard.press('Escape');
  check(await page.locator('#record-menu').evaluate(el => !el.open && document.activeElement === el.querySelector('summary')), 'Escape closes menu and restores focus');
  check(await page.locator('#record-menu > summary').evaluate(el => getComputedStyle(el).outlineStyle !== 'none'), 'visible keyboard focus');
  check(await page.locator('#prediction-forward-marker').isHidden(), 'no preselected prediction');
  const track = page.locator('#prediction-track');
  await track.scrollIntoViewIfNeeded();
  const bounds = await track.boundingBox();
  if (width === 390) await track.tap({ position: { x: bounds.width * .15, y: 20 } });
  else await track.click({ position: { x: bounds.width * .15, y: 20 } });
  check(await page.locator('#prediction-forward').inputValue() === '15', 'coarse F placement by mouse or touch');
  await page.locator('[data-prediction-primer=reverse]').click();
  await track.click({ position: { x: bounds.width * .75, y: 20 } });
  await page.locator('#prediction-reverse').focus(); await page.keyboard.press('ArrowRight');
  check(await page.locator('#prediction-reverse').inputValue() === '80', 'keyboard prediction handle');
  check((await page.locator('#prediction-forward-value').innerText()).includes('왼쪽'), 'relative position without bp calculation');
  await page.locator('#activity-00').screenshot({ animations: 'disabled', path: resolve(output, `${engine}-${width}-intro00.png`) });

  const mixed = await page.locator('#cycle-svg .pcr-strand').first().getAttribute('d');
  await page.locator('#cycle-next').click();
  check((await page.locator('#cycle-title').innerText()).includes('변성'), 'next moves from mixture to denaturation');
  check(await page.locator('#cycle-svg .pcr-strand').first().getAttribute('d') !== mixed, 'denaturation separates actual DNA geometry');
  check(await page.locator('[data-mixture=template]').getAttribute('data-active') === 'true', 'template emphasis');
  await page.locator('[data-cycle-stage=annealing]').click();
  check(await page.locator('#cycle-svg .pcr-intro-primer').count() === 4, 'both bound primers and arrowheads');
  check(await page.locator('#cycle-svg .pcr-boundary-guide').count() === 1, 'primer boundary guide');
  check(await page.locator('[data-mixture=forward]').getAttribute('data-active') === 'true', 'primer emphasis');
  await page.locator('#cycle-next').click();
  check(await page.locator('#cycle-svg .pcr-new-dna').count() === 4 && await page.locator('#cycle-svg .pcr-pol').count() === 2, 'extension and two Pol markers');
  check(await page.locator('#cycle-next').isDisabled(), 'last stage has explicit navigation bound');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  check(await page.locator('.pcr-line-growth').first().evaluate(el => getComputedStyle(el).animationName) === 'none', 'reduced motion removes line growth');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.locator('#cycle-prev').click(); check(await page.locator('[data-cycle-stage=annealing]').getAttribute('aria-pressed') === 'true', 'previous stage state');
  await page.locator('[data-cycle-stage=extension]').click();
  await page.locator('[data-comparison-cycle="2"]').click();
  check((await page.locator('#cycle-products-description').innerText()).includes('단일가닥'), 'second cycle exact single strand');
  await page.locator('[data-comparison-cycle="3"]').click();
  check((await page.locator('#cycle-products-description').innerText()).includes('이중가닥'), 'third cycle exact duplex');
  await page.locator('input[name=cycle-boundary-choice][value=polymerase]').check();
  check((await page.locator('#cycle-choice-feedback').innerText()).includes('다시'), 'incorrect boundary feedback');
  await page.locator('input[name=cycle-boundary-choice][value=primer-pair]').check();
  check(await page.locator('#cycle-selector').isHidden(), 'redundant prompt retained only for legacy records');
  await page.locator('#activity-01').screenshot({ animations: 'disabled', path: resolve(output, `${engine}-${width}-intro01.png`) });

  await page.locator('[data-arrangement=parallel]').click();
  check((await page.locator('#arrangement-description').innerText()).includes('같은 가닥'), 'wrong pair explains strand and synthesis direction');
  const wrong = await page.locator('#direction-svg').innerHTML();
  await page.locator('#flip-strands').click();
  check((await page.locator('#direction-caption').innerText()).includes('아래쪽'), 'reference moves below');
  check(await page.locator('#direction-svg').innerHTML() !== wrong, 'strand flip changes geometry');
  await page.locator('[data-arrangement=inward]').click();
  check((await page.locator('#arrangement-description').innerText()).includes('서로를 향해'), 'inward comparison');
  await page.locator('#direction-complement').fill('AAAAAAAA'); await page.locator('#check-complement').click();
  check(await page.locator('#reverse-step').isHidden(), 'incorrect complement does not unlock reverse');
  await page.locator('#direction-complement').fill('TCAGGCAT'); await page.locator('#check-complement').click();
  check(await page.locator('#reverse-step').isVisible() && await page.locator('#reverse-demonstration').isHidden(), 'correct complement unlocks second operation');
  await page.locator('#reverse-complement').click();
  check((await page.locator('#reverse-demonstration').innerText()).includes('T A C G G A C T'), 'reverse operation demonstrated');
  await page.locator('#direction-reverse').fill('TACGGACT'); await page.locator('#check-direction').click();
  check((await page.locator('#direction-feedback').innerText()).includes('일치합니다'), 'order sequence check');
  await page.locator('input[name=direction-end-choice][value="3"]').check();
  check(await page.locator('#direction-reason').isHidden(), 'redundant prompt retained only for legacy records');
  await page.locator('#activity-02').screenshot({ animations: 'disabled', path: resolve(output, `${engine}-${width}-intro02.png`) });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'intro interactions do not overflow viewport');
  await page.reload(); await page.waitForSelector('#pcr-worksheet[data-ready=true]');
  check(await page.locator('#prediction-forward').inputValue() === '15' && await page.locator('#prediction-reverse').inputValue() === '80', 'prediction autosaved');
  check(await page.locator('[data-cycle-stage=extension]').getAttribute('aria-pressed') === 'true', 'stage restored');
  check(await page.locator('[data-comparison-cycle="3"]').getAttribute('aria-pressed') === 'true', 'comparison restored');
  check(await page.locator('input[name=cycle-boundary-choice][value=primer-pair]').isChecked(), 'boundary answer restored');
  check(await page.locator('#reverse-demonstration').isVisible(), 'two-step exercise restored');
  await page.locator('#activity-02').scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelector('.pcr-sidebar a[href="#activity-02"]').getAttribute('aria-current') === 'location');
  check(await page.locator('.pcr-sidebar a[aria-current]').count() === 1, 'one current activity marked');
}
